/**
 * Smart Rule-Based Financial Recommendation Engine - India Context
 */

// Helper to format currency in Indian Rupees (₹)
const formatINR = (val) => '₹' + Number(val || 0).toLocaleString('en-IN');

const generateRecommendations = ({
  monthlyIncome = 0,
  currentSavings = 0,
  monthlyExpenses = 0,
  actualExpenses = 0,
  goals = [],
  inflationRate = 6.0
}) => {
  const recommendations = [];

  const monthlyBurn = monthlyExpenses > 0 ? monthlyExpenses : 45000;
  const recommendedEmergencyFund = monthlyBurn * 3;
  const isSavingsLow = currentSavings < recommendedEmergencyFund;

  let recommendedPlan = 'Cash Savings';
  let planReasoning = '';

  if (isSavingsLow) {
    recommendedPlan = 'Cash Savings';
    planReasoning = `Your liquid reserves (${formatINR(currentSavings)}) are below the recommended 3-month emergency buffer (${formatINR(recommendedEmergencyFund)}). Prioritize high-liquidity Cash Savings first.`;
  } else if (currentSavings >= recommendedEmergencyFund && currentSavings < monthlyBurn * 12) {
    recommendedPlan = 'Bank Savings';
    planReasoning = `You have an established emergency buffer! Transfer surplus capital into High-Yield Bank FDs/Savings (${formatINR(currentSavings)}) to protect cash from inflation while maintaining stability.`;
  } else {
    recommendedPlan = 'Investment';
    planReasoning = `You possess robust liquid reserves (${formatINR(currentSavings)}). Allocate growth capital into Nifty 50 Index Funds & Sovereign Gold Bonds to achieve real positive returns above current ${inflationRate}% CPI inflation.`;
  }

  recommendations.push({
    id: 'rec_plan',
    type: 'PLAN_RECOMMENDATION',
    priority: 'HIGH',
    title: `Recommended Strategy: ${recommendedPlan}`,
    description: planReasoning,
    action: `Switch to ${recommendedPlan}`,
    recommendedPlan
  });

  if (actualExpenses > monthlyExpenses && monthlyExpenses > 0) {
    const overspendAmount = actualExpenses - monthlyExpenses;
    const pctOver = Math.round((overspendAmount / monthlyExpenses) * 100);
    recommendations.push({
      id: 'rec_alert_overspend',
      type: 'SPENDING_WARNING',
      priority: 'CRITICAL',
      title: 'Spending Warning: Actual Exceeds Planned Budget',
      description: `Your actual monthly expenses (${formatINR(actualExpenses)}) exceed your planned budget (${formatINR(monthlyExpenses)}) by ${formatINR(overspendAmount)} (+${pctOver}%). Reduce non-essential discretionary categories.`,
      action: 'Review Planned vs Actual Breakdown'
    });
  }

  if (goals.length > 0) {
    const highestGoal = goals.reduce((max, g) => (g.targetAmount > max.targetAmount ? g : max), goals[0]);
    if (highestGoal && highestGoal.inflationAdjustedTarget > highestGoal.targetAmount) {
      const inflationDelta = highestGoal.inflationAdjustedTarget - highestGoal.targetAmount;
      recommendations.push({
        id: 'rec_goal_inflation',
        type: 'GOAL_ADJUSTMENT',
        priority: 'MEDIUM',
        title: `Inflation Target Surge for "${highestGoal.goalName}"`,
        description: `Due to projected ${inflationRate}% CPI inflation in India, your target increases by ${formatINR(Math.round(inflationDelta))} to ${formatINR(Math.round(highestGoal.inflationAdjustedTarget))}. Consider increasing monthly SIPs by 5-10% annually.`,
        action: 'Update Goal Contribution'
      });
    }
  }

  const disclaimer = 'Notice: Recommendations generated by InflationWise are educational simulation insights based on your inputs and do not constitute certified professional financial advice.';

  return {
    recommendedPlan,
    insights: recommendations,
    disclaimer
  };
};

module.exports = {
  generateRecommendations
};
